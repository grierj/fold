// Command zonegen writes zones_list.go from the system's zone1970.tab: every
// canonical IANA zone, so setup offers them all (docs/HAZARDS.md section 1).
// Run with: go generate ./internal/app
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"
	"time"
)

func main() {
	f, err := os.Open("/usr/share/zoneinfo/zone1970.tab")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	seen := map[string]bool{"UTC": true}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") || line == "" {
			continue
		}
		cols := strings.Split(line, "\t")
		if len(cols) >= 3 {
			if _, err := time.LoadLocation(cols[2]); err == nil {
				seen[cols[2]] = true
			}
		}
	}
	var zones []string
	for z := range seen {
		zones = append(zones, z)
	}
	sort.Strings(zones)
	out, _ := os.Create("zones_list.go")
	defer out.Close()
	fmt.Fprintln(out, "// Code generated by zonegen from zone1970.tab; DO NOT EDIT.")
	fmt.Fprintln(out, "\npackage app\n\nvar zoneNames = []string{")
	for _, z := range zones {
		fmt.Fprintf(out, "\t%q,\n", z)
	}
	fmt.Fprintln(out, "}")
}
