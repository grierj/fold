// erasureColumn records coverage of the inventory in
// docs/plan/M7.4-ERASURE-INVENTORY.md, section 4. It has no runtime caller.
// Row names the table heading; Rules names headings or row IDs to consult.
// A reference records a disposition and its gates, not approval of retention
// or proof that a future erasure slice has implemented it.
