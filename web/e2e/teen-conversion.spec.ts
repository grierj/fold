import AxeBuilder from "@axe-core/playwright";
import { expect, test, type Page } from "@playwright/test";
import { apiAs, email, PASSWORD, signIn, signOut } from "./helpers";

async function shoot(page: Page, name: string) {
  if (!process.env.SCREENS_DIR) return;
  for (const width of [390, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: `${process.env.SCREENS_DIR}/${name}-${width}.png`, fullPage: true });
    const household = page.getByRole("region", { name: "My household", exact: true });
    if (await household.count()) await household.screenshot({ path: `${process.env.SCREENS_DIR}/${name}-household-${width}.png`, style: "header, nav[aria-label='Tabs'] { visibility: hidden; }" });
  }
}

test("a household keeps its teen's sign-up until approval, consent, and the new guardian check complete", async ({ page, request }) => {
  test.setTimeout(45_000);
  test.skip((await request.get("/dev/outbox")).status() !== 200, "Requires dev outbox to open the conversion email");
  const admin = await apiAs(request, "grier");
  const parentName = "teen-conversion-parent";
  const ownName = "teen-conversion-own";
  const { user: parent } = await admin("POST", "/admin/users", { name: "Teen Conversion Parent", email: email(parentName), password: PASSWORD, role: "member", ageBand: "adult" });
  const { group } = await admin("POST", "/groups", { name: "Teen conversion evening", visibility: "public", tags: [] });
  const start = new Date(Date.now() + 7 * 86400_000).toISOString().slice(0, 16);
  const { event } = await admin("POST", `/groups/${group.id}/events`, { title: "Teen conversion date", startsLocal: start, durationMinutes: 60, tzid: "UTC", capacity: 1, waitlistEnabled: true });
  await signIn(page, parentName);
  const parentApi = await apiAs(page.request, parentName);
  const birth = new Date(); birth.setFullYear(birth.getFullYear() - 15);
  const { person } = await parentApi("POST", "/me/household/people", { firstName: "Taylor Conversion", kind: "teen", birthDate: birth.toISOString().slice(0, 10) });
  await admin("POST", `/admin/guardian-links/${person.guardianLinkId}/confirm`, { checkNote: "Known original household" });
  const registered = await parentApi("PUT", `/events/${event.id}/registrations`, { date: start.slice(0, 10), people: [{ personId: person.id, status: "going" }] });
  const registrationId = registered.people[0].registrationId;
  await page.goto("/profile");
  await page.getByRole("button", { name: "Create their own account" }).click();
  await expect(page.getByText(/The guardian link for the new account needs a fresh admin check/)).toBeVisible();
  await page.getByLabel("Their email address").fill(email(ownName));
  await shoot(page, "teen-conversion-invitation");
  await page.getByRole("button", { name: "Send account invitation" }).click();
  await expect(page.getByText(`Invitation pending: ${email(ownName)}`, { exact: false })).toBeVisible();
  const html = await (await request.get("/dev/outbox")).text();
  const section = html.split("<section").find((part) => part.includes(`To: ${email(ownName)}`));
  const link = section?.match(/https?:[^\s<]+\/invite\?token=[A-Za-z0-9_-]+/)?.[0];
  expect(link).toBeTruthy();
  if (!link) throw new Error("Conversion email did not contain its invitation");
  await signOut(page);
  await page.goto(new URL(link).pathname + new URL(link).search);
  await expect(page.getByText(/consent is granted, and the new guardian link is confirmed/)).toBeVisible();
  await page.getByLabel("Choose a password").fill(PASSWORD);
  await shoot(page, "teen-conversion-accept");
  await page.getByRole("button", { name: "Create my account" }).click();
  await expect(page.getByRole("heading", { name: "Your account is almost ready" })).toBeVisible();
  expect((await page.request.get("/api/v1/auth/me")).status()).toBe(401);
  const { requests } = await admin("GET", "/admin/account-requests");
  const pending = requests.find((row: { email: string }) => row.email === email(ownName));
  expect(pending).toBeTruthy();
  await admin("POST", `/admin/account-requests/${pending.id}/approve`, { accountConsentEvidenceText: "Signed paper form for this teen" });
  const { users } = await admin("GET", "/admin/users");
  const teen = users.find((row: { email: string }) => row.email === email(ownName));
  expect(teen).toMatchObject({ accountType: "teen", status: "pending_consent" });
  await signIn(page, parentName);
  await page.goto("/profile");
  await expect(page.getByText("Account waiting for consent and guardian confirmation", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Remove Taylor Conversion" })).toBeDisabled();
  await shoot(page, "teen-conversion-household-waiting");
  await page.getByRole("button", { name: "Edit Taylor Conversion" }).click();
  await expect(page.getByLabel("First name", { exact: true })).toHaveAttribute("readonly", "");
  await page.getByLabel(/^Care notes/).fill("Care remains with household until ready");
  await shoot(page, "teen-conversion-household-edit");
  const axe = await new AxeBuilder({ page }).analyze();
  expect(axe.violations.filter((violation) => violation.impact === "serious" || violation.impact === "critical")).toEqual([]);
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Care notes: Care remains with household until ready")).toBeVisible();
  const before = await parentApi("GET", `/events/${event.id}`);
  expect(before.occurrences[0].myHouseholdRegistrations).toEqual(expect.arrayContaining([expect.objectContaining({ personId: person.id, registrationId, status: "going" })]));
  const { guardianLinks } = await admin("GET", "/admin/guardian-links");
  const freshLink = guardianLinks.find((row: { teenUserId?: number; guardianUserId: number }) => row.teenUserId === teen.id && row.guardianUserId === parent.id);
  expect(freshLink).toMatchObject({ status: "pending" });
  await signIn(page, ownName);
  await expect(page.getByRole("heading", { name: "Waiting for consent" })).toBeVisible();
  expect((await page.request.get("/api/v1/events")).status()).toBe(403);
  await admin("POST", `/admin/guardian-links/${freshLink.id}/confirm`, { checkNote: "Fresh teen-account guardian check" });
  await page.getByRole("button", { name: "Check account status" }).click();
  await expect(page.getByRole("heading", { name: "Waiting for consent" })).toHaveCount(0);
  const after = await (await page.request.get(`/api/v1/events/${event.id}`)).json();
  expect(after.occurrences[0].myRegistration).toBe("going");
  const roster = await admin("GET", `/events/${event.id}`);
  expect(roster.occurrences[0].attendees).toEqual(expect.arrayContaining([expect.objectContaining({ userId: teen.id, registrationId, status: "going", accountType: "teen" })]));
  await signIn(page, parentName);
  await page.goto("/profile");
  await expect(page.getByText("Account waiting for consent and guardian confirmation")).toHaveCount(0);
  const household = await parentApi("GET", "/me/household");
  expect(household.household.people.some((row: { id: number }) => row.id === person.id)).toBe(false);
  expect(household.household.accounts).toEqual(expect.arrayContaining([expect.objectContaining({ userId: teen.id, relation: "teen" })]));
  await shoot(page, "teen-conversion-complete");
});
